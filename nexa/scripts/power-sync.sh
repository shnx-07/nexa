#!/usr/bin/env bash

# NEXA Power & Sleep Idle Synchronization
# ---------------------------------------
# Reads ~/.config/nexa/config/power.json, checks AC/Battery status,
# generates ~/.config/hypr/hypridle.conf, and restarts hypridle cleanly.

CONFIG_FILE="$HOME/.config/nexa/config/power.json"
HYPRIDLE_CONF="$HOME/.config/hypr/hypridle.conf"
LOCK_SCRIPT="$HOME/.config/hypr/scripts/lock.sh"

if [[ ! -f "$CONFIG_FILE" ]]; then
  exit 0
fi

# Detect whether we are on AC or Battery via upower / sysfs
ON_BATTERY=false
if command -v upower >/dev/null 2>&1; then
  if upower -d | grep -i "on-battery" | grep -q "yes"; then
    ON_BATTERY=true
  fi
elif [[ -d /sys/class/power_supply ]]; then
  for ac in /sys/class/power_supply/A*/online /sys/class/power_supply/AC*/online; do
    if [[ -f "$ac" && "$(cat "$ac")" == "0" ]]; then
      ON_BATTERY=true
      break
    fi
  done
fi

if [[ "$ON_BATTERY" == true ]]; then
  LOCK_TIMEOUT=$(jq -r '.lock_battery // 180' "$CONFIG_FILE")
  SCREEN_OFF_TIMEOUT=$(jq -r '.screen_off_battery // 300' "$CONFIG_FILE")
  SLEEP_TIMEOUT=$(jq -r '.sleep_battery // 900' "$CONFIG_FILE")
else
  LOCK_TIMEOUT=$(jq -r '.lock_ac // 300' "$CONFIG_FILE")
  SCREEN_OFF_TIMEOUT=$(jq -r '.screen_off_ac // 600' "$CONFIG_FILE")
  SLEEP_TIMEOUT=$(jq -r '.sleep_ac // 1800' "$CONFIG_FILE")
fi

# Generate hypridle.conf
cat > "$HYPRIDLE_CONF" << CONF
# Generated by NEXA Power & Sleep Management
# Do not edit manually. Changes will be overwritten by NEXA Settings.

general {
    lock_cmd = ${LOCK_SCRIPT}
    before_sleep_cmd = ${LOCK_SCRIPT}
    after_sleep_cmd = hyprctl dispatch 'hl.dsp.dpms("on")'

    ignore_dbus_inhibit = false
    ignore_systemd_inhibit = false
}
CONF

# Listener 1: Lock Screen
if [[ "$LOCK_TIMEOUT" -gt 0 ]]; then
cat >> "$HYPRIDLE_CONF" << CONF

listener {
    timeout = ${LOCK_TIMEOUT}
    on-timeout = ${LOCK_SCRIPT}
}
CONF
fi

# Listener 2: Turn off screen backlight (safe for all GPU KMS)
if [[ "$SCREEN_OFF_TIMEOUT" -gt 0 ]]; then
cat >> "$HYPRIDLE_CONF" << CONF

listener {
    timeout = ${SCREEN_OFF_TIMEOUT}
    on-timeout = brightnessctl -s set 0
    on-resume = brightnessctl -r && hyprctl dispatch 'hl.dsp.dpms("on")'
}
CONF
fi

# Listener 3: Suspend system to RAM
if [[ "$SLEEP_TIMEOUT" -gt 0 ]]; then
cat >> "$HYPRIDLE_CONF" << CONF

listener {
    timeout = ${SLEEP_TIMEOUT}
    on-timeout = systemctl suspend
}
CONF
fi

# Restart hypridle cleanly
pkill -x hypridle 2>/dev/null || true
sleep 0.1
nohup hypridle >/dev/null 2>&1 &
